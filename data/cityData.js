export const getCityData = (cityId) => {
  return cityData[cityId] || null;
};

export const getAllCities = () => {
  return Object.values(cityData);
};

export const searchPOIs = (query) => {
  const results = [];
  const lowerQuery = query.toLowerCase();
  
  Object.values(cityData).forEach(city => {
    city.pois.forEach(poi => {
      if (
        poi.name.toLowerCase().includes(lowerQuery) ||
        poi.description.toLowerCase().includes(lowerQuery) ||
        poi.category.toLowerCase().includes(lowerQuery)
      ) {
        results.push({
          ...poi,
          city: city.name,
          cityId: city.id
        });
      }
    });
  });
  
  return results;
};
